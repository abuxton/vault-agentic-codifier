"""
headers — provenance header writer for generated Terraform/HCL files.

Implements: TASK-004a
Spec ref:   specs.md §CAC7 (provenance header on every generated file)
Doc ref:    https://developer.hashicorp.com/vault/docs
            https://developer.hashicorp.com/validated-designs/vault/administration-guide/introduction

Every file produced by the codifier begins with a standard header comment that:
  1. Identifies the tool that produced it (never edit by hand).
  2. Names the owning capability slug (from constants.CAPABILITY_ORDER).
  3. Cites the documentation URL that justifies the resource-type mapping.
  4. Records the Vault cluster address and namespace scope (never the token).
  5. Embeds a UTC timestamp for the codification run.

The ``doc_url_map`` below is seeded from ``tmp/terraform-resource-map.md`` and
the two validated-design paths named in specs.md.  It maps capability slug →
primary documentation URL.
"""

from __future__ import annotations

import datetime
from typing import Dict, Optional

# ---------------------------------------------------------------------------
# Documentation URL map per capability (seeded from tmp/terraform-resource-map.md
# and the validated-design paths in specs.md)
# ---------------------------------------------------------------------------
DOC_URL_MAP: Dict[str, str] = {
    "root-config": (
        "https://developer.hashicorp.com/vault/api-docs/system"
    ),
    "admin-config": (
        "https://developer.hashicorp.com/validated-designs/vault/"
        "administration-guide/authentication-for-people"
    ),
    "auth-mounts": (
        "https://developer.hashicorp.com/vault/api-docs/system/auth"
    ),
    "secrets-engines": (
        "https://developer.hashicorp.com/vault/api-docs/system/mounts"
    ),
    "namespaces": (
        "https://developer.hashicorp.com/vault/api-docs/system/namespaces"
    ),
    "policies": (
        "https://developer.hashicorp.com/vault/docs/concepts/policies"
    ),
    "teams": (
        "https://developer.hashicorp.com/vault/api-docs/secret/identity/group"
    ),
}

# Fallback for capabilities not in the map
_DEFAULT_DOC_URL = "https://developer.hashicorp.com/vault/docs"

# Header template — uses `#` comments so it is valid in both .tf and .hcl files
_HEADER_TEMPLATE = """\
# =============================================================================
# Generated by vault-brownfield-codifier — DO NOT EDIT BY HAND
# Regenerate with: python -m codifier
#
# Capability : {capability}
# Layer      : {layer}
# Namespace  : {namespace}
# Doc ref    : {doc_url}
# Generated  : {timestamp}
# =============================================================================
"""


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def file_header(
    capability: str,
    layer: str,
    namespace: str = "",
    doc_url: Optional[str] = None,
    timestamp: Optional[datetime.datetime] = None,
) -> str:
    """
    Return the standard provenance header string for a generated file.

    Parameters
    ----------
    capability:
        One of the capability slugs from ``constants.CAPABILITY_ORDER``
        (e.g. ``"namespaces"``, ``"policies"``).
    layer:
        Terraform state layer (``"admin"``, ``"namespaces"``, or ``"seed"``).
    namespace:
        The Vault namespace this file targets.  Empty string = root namespace.
    doc_url:
        Override the documentation URL.  When ``None``, looked up from
        ``DOC_URL_MAP`` by capability.
    timestamp:
        UTC datetime for the generation run.  Defaults to ``datetime.datetime.utcnow()``.

    Returns
    -------
    str
        Multi-line comment block ending with a newline, ready to prepend to any
        HCL / Terraform file.
    """
    if doc_url is None:
        doc_url = DOC_URL_MAP.get(capability, _DEFAULT_DOC_URL)
    if timestamp is None:
        timestamp = datetime.datetime.utcnow()
    ns_display = namespace if namespace else "(root)"
    ts_str = timestamp.strftime("%Y-%m-%dT%H:%M:%SZ")
    return _HEADER_TEMPLATE.format(
        capability=capability,
        layer=layer,
        namespace=ns_display,
        doc_url=doc_url,
        timestamp=ts_str,
    )


def prepend_header(
    content: str,
    capability: str,
    layer: str,
    namespace: str = "",
    doc_url: Optional[str] = None,
    timestamp: Optional[datetime.datetime] = None,
) -> str:
    """
    Prepend the standard provenance header to ``content`` and return the result.

    Parameters
    ----------
    content:
        The body of the generated Terraform/HCL file (without any header).
    capability, layer, namespace, doc_url, timestamp:
        Forwarded to :func:`file_header`.

    Returns
    -------
    str
        Header + content, with a single blank line separating them.
    """
    header = file_header(
        capability=capability,
        layer=layer,
        namespace=namespace,
        doc_url=doc_url,
        timestamp=timestamp,
    )
    return header + "\n" + content
