"""
providers — provider and version-pin template generator.

Implements: TASK-002
Spec ref:   specs.md §Namespace targeting in generated HCL; ADR-002 (skip_child_token)
Doc ref:    https://developer.hashicorp.com/vault/docs/configuration
            https://registry.terraform.io/providers/hashicorp/vault/latest/docs

Emits the two standard files for every generated Terraform layer:
  • providers.tf  — required_providers block + provider "vault" blocks
  • versions.tf   — terraform { required_version } block

No token, address or licence value is ever embedded in template output (CAC3).
Credentials are supplied through VAULT_ADDR / VAULT_TOKEN environment variables
or sensitive input variables (no default value).

Namespace-targeting style is set at construction time via `namespace_style`:
  "aliased"   — provider blocks per namespace alias (provider = vault.<alias>)
  "resource"  — single provider block; namespace set per-resource in HCL
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional

# ---------------------------------------------------------------------------
# Version constants
# ---------------------------------------------------------------------------
TERRAFORM_MIN_VERSION = ">= 1.9"
VAULT_PROVIDER_VERSION = "~> 4"
VAULT_PROVIDER_SOURCE = "hashicorp/vault"

# Layer 1 = admin/ (root namespace)  → skip_child_token = true
# Layer 2 = namespaces/              → skip_child_token = true
# Layer 3 = seed/ (tenant ns)        → skip_child_token = false (child tokens needed)
LAYER_SKIP_CHILD_TOKEN: Dict[str, bool] = {
    "admin": True,
    "namespaces": True,
    "seed": False,
}

# ---------------------------------------------------------------------------
# Data model
# ---------------------------------------------------------------------------

@dataclass
class ProviderAlias:
    """Represents a single aliased vault provider block."""
    alias: str           # e.g. "admin", "platform"
    namespace: str       # e.g. "admin", "admin/platform"
    skip_child_token: bool = True


@dataclass
class ProviderConfig:
    """
    Configuration for a generated Terraform layer.

    Parameters
    ----------
    layer:
        One of "admin", "namespaces", "seed".
    namespace_style:
        "aliased"  — one provider alias per namespace in this layer.
        "resource" — a single default provider; namespace set per resource.
    aliases:
        For "aliased" style: list of ProviderAlias entries.
        The *first* entry is treated as the default (unaliased) provider.
        Ignored when namespace_style == "resource".
    extra_vars:
        Additional sensitive variable declarations to append to versions.tf
        (e.g. a custom CA cert path). Format: ``{var_name: description}``.
    """
    layer: str
    namespace_style: str = "aliased"          # "aliased" | "resource"
    aliases: List[ProviderAlias] = field(default_factory=list)
    extra_vars: Dict[str, str] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if self.namespace_style not in ("aliased", "resource"):
            raise ValueError(
                f"namespace_style must be 'aliased' or 'resource', got {self.namespace_style!r}"
            )
        if self.layer not in LAYER_SKIP_CHILD_TOKEN:
            raise ValueError(
                f"layer must be one of {list(LAYER_SKIP_CHILD_TOKEN)}, got {self.layer!r}"
            )


# ---------------------------------------------------------------------------
# Rendering helpers
# ---------------------------------------------------------------------------

def _indent(text: str, spaces: int = 2) -> str:
    pad = " " * spaces
    return "\n".join(pad + line if line.strip() else line for line in text.splitlines())


def _render_versions_tf(cfg: ProviderConfig) -> str:
    """Return the content of ``versions.tf`` for a layer."""
    lines: List[str] = [
        "# Generated by vault-brownfield-codifier",
        "# DO NOT EDIT — regenerate with: python -m codifier",
        "#",
        "# Credentials are supplied via environment variables or sensitive variables.",
        "# VAULT_ADDR and VAULT_TOKEN must be set before plan/apply.",
        "",
        "terraform {",
        f'  required_version = "{TERRAFORM_MIN_VERSION}"',
        "",
        "  required_providers {",
        "    vault = {",
        f'      source  = "{VAULT_PROVIDER_SOURCE}"',
        f'      version = "{VAULT_PROVIDER_VERSION}"',
        "    }",
        "  }",
        "}",
        "",
        "# ---------------------------------------------------------------------------",
        "# Sensitive input variables — values are NEVER hard-coded here.",
        "# Set via TF_VAR_vault_token / TF_VAR_vault_address or environment variables.",
        "# ---------------------------------------------------------------------------",
        "",
        'variable "vault_address" {',
        '  description = "Vault cluster address (https://…). Defaults to VAULT_ADDR env var."',
        "  type        = string",
        "  sensitive   = false",
        '  default     = null  # resolved from VAULT_ADDR',
        "}",
        "",
        'variable "vault_token" {',
        '  description = "Vault token for this layer. Sensitive — set via TF_VAR_vault_token or VAULT_TOKEN."',
        "  type        = string",
        "  sensitive   = true",
        "  default     = null  # resolved from VAULT_TOKEN",
        "}",
    ]

    for var_name, description in sorted(cfg.extra_vars.items()):
        lines += [
            "",
            f'variable "{var_name}" {{',
            f'  description = "{description}"',
            "  type        = string",
            "  sensitive   = true",
            "  default     = null",
            "}",
        ]

    lines.append("")
    return "\n".join(lines)


def _render_single_provider_block(
    alias: Optional[str],
    namespace: Optional[str],
    skip_child_token: bool,
    is_default: bool = False,
) -> List[str]:
    """Return lines for one ``provider "vault" { … }`` block."""
    lines = ['provider "vault" {']
    if alias and not is_default:
        lines.append(f'  alias = "{alias}"')
    if namespace:
        lines.append(f'  namespace = "{namespace}"')
    lines.append(f"  skip_child_token = {str(skip_child_token).lower()}")
    lines.append(
        "  address = var.vault_address  # falls back to VAULT_ADDR env var"
    )
    lines.append(
        "  token   = var.vault_token    # falls back to VAULT_TOKEN env var"
    )
    lines.append("}")
    return lines


def _render_providers_tf(cfg: ProviderConfig) -> str:
    """Return the content of ``providers.tf`` for a layer."""
    layer_skip = LAYER_SKIP_CHILD_TOKEN[cfg.layer]
    header = [
        "# Generated by vault-brownfield-codifier",
        "# DO NOT EDIT — regenerate with: python -m codifier",
        "",
    ]

    blocks: List[str] = []

    if cfg.namespace_style == "resource":
        # Single default provider — namespace is set per resource in HCL.
        blocks += _render_single_provider_block(
            alias=None,
            namespace=None,
            skip_child_token=layer_skip,
            is_default=True,
        )
        blocks.append(
            "# Note: namespace is set per resource (namespace_style = resource)."
        )

    else:  # aliased
        if not cfg.aliases:
            # Fallback: single unaliased provider for the layer's root namespace.
            blocks += _render_single_provider_block(
                alias=None,
                namespace=None,
                skip_child_token=layer_skip,
                is_default=True,
            )
        else:
            for i, pa in enumerate(cfg.aliases):
                is_default = i == 0
                blocks += _render_single_provider_block(
                    alias=pa.alias,
                    namespace=pa.namespace,
                    skip_child_token=pa.skip_child_token,
                    is_default=is_default,
                )
                blocks.append("")

    return "\n".join(header) + "\n".join(blocks) + "\n"


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

def render_versions_tf(cfg: ProviderConfig) -> str:
    """Return the content of ``versions.tf`` for the given layer config."""
    return _render_versions_tf(cfg)


def render_providers_tf(cfg: ProviderConfig) -> str:
    """Return the content of ``providers.tf`` for the given layer config."""
    return _render_providers_tf(cfg)


def default_config_for_layer(layer: str, namespace_style: str = "aliased") -> ProviderConfig:
    """
    Return a sensible default ProviderConfig for a given layer.

    For "aliased" style the aliases list is left empty; callers should populate
    it from the namespace discovery payloads.
    """
    return ProviderConfig(layer=layer, namespace_style=namespace_style)


def admin_layer_config(namespace_style: str = "aliased") -> ProviderConfig:
    """Standard config for the admin/ layer (root namespace, skip_child_token = true)."""
    return ProviderConfig(
        layer="admin",
        namespace_style=namespace_style,
        aliases=[
            ProviderAlias(alias="root", namespace="", skip_child_token=True),
        ],
    )


def namespaces_layer_config(
    admin_ns: str = "admin",
    namespace_style: str = "aliased",
) -> ProviderConfig:
    """Standard config for the namespaces/ layer."""
    return ProviderConfig(
        layer="namespaces",
        namespace_style=namespace_style,
        aliases=[
            ProviderAlias(alias="admin", namespace=admin_ns, skip_child_token=True),
        ],
    )


def seed_layer_config(
    tenant_namespaces: List[str],
    namespace_style: str = "aliased",
) -> ProviderConfig:
    """Standard config for the seed/ layer, one alias per tenant namespace."""
    aliases = [
        ProviderAlias(
            alias=ns.replace("/", "_").replace("-", "_"),
            namespace=ns,
            skip_child_token=False,
        )
        for ns in tenant_namespaces
    ]
    return ProviderConfig(layer="seed", namespace_style=namespace_style, aliases=aliases)
