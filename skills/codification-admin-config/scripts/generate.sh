#!/usr/bin/env bash
# codification-admin-config (TASK-021)
#   generate.sh [raw-dir] [out-root]
# Reads <raw>/admin/admin_config.json and writes the admin-layer composition under <out-root>/admin:
#   main.tf                    locals that reference policies and groups owned by other skills
#   outputs.tf                 namespace path, operator policy names, auth mount accessors
#   human_auth.tf              only when a top-level oidc, jwt or ldap mount exists (+ its variables)
#   imports_admin_config.tf    only with human_auth.tf
#   admin_config_README.md     operator policies, holders, human auth status
# This skill references; it does not re-declare. The only resources it declares are
# vault_jwt_auth_backend(_role) and vault_ldap_auth_backend(_group). oidc_client_secret and bindpass
# become sensitive variables with no default. Run after namespaces, policies, auth-mounts and teams.
# Import IDs (provider docs): backend = path; jwt role = auth/<path>/role/<name>; ldap group = auth/<path>/groups/<name>.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
RAW=${1:-discovered_terraform/raw}
OUT=${2:-discovered_terraform/terraform}
TF=${TERRAFORM:-terraform}
DOC=https://registry.terraform.io/providers/hashicorp/vault/4.8.0/docs/resources
scaffold=$here/../../vault-codifier-conventions/scripts/scaffold-layer.sh
L=$OUT/admin
CFG=$RAW/admin/admin_config.json
{ test -s "$CFG" && jq -e '.operator_policies|type=="array"' "$CFG" >/dev/null; } \
  || { echo "STOP: $CFG missing or unparseable" >&2; exit 2; }
[ -s "$RAW/admin/policies.json" ] || { echo "STOP: $RAW/admin/policies.json missing" >&2; exit 2; }

# credential guard: a secret field must be absent, empty or "REDACTED"
if jq -e '[.human_auth_mounts[]? | .. | objects | to_entries[]
           | select((.key|IN("client_secret","oidc_client_secret","bindpass")) and (.value|type=="string") and .value != "" and .value != "REDACTED")] | length > 0' "$CFG" >/dev/null; then
  echo "STOP: $CFG holds an unmasked secret in a human auth payload (value not printed)" >&2; exit 2
fi

read -r -d '' LIB <<'JQ' || true
def lbl: ascii_downcase | gsub("[/+. -]+";"_") | gsub("_+";"_") | sub("^_";"") | sub("_$";"")
         | if test("^[0-9]") then "r_"+. else . end | if .=="" then "_empty" else . end;
def mref($t; $l): (if ($t|IN("oidc","jwt")) then "vault_jwt_auth_backend" elif $t == "ldap" then "vault_ldap_auth_backend" else "vault_auth_backend" end) + "." + $l;
JQ

# every referenced resource must already be generated by its owning skill
need() { grep -qsE "^resource \"$1\" \"$2\"" "$L"/*.tf || { echo "STOP: $1.$2 is not declared in $L; run the owning skill first" >&2; exit 2; }; }
need vault_namespace admin
for p in $(jq -r '.operator_policies[]|"vault_policy admin_"+(.|ascii_downcase|gsub("[/+. -]+";"_"))' "$CFG" | tr ' ' ':'); do need "${p%%:*}" "${p##*:}"; done
for g in $(jq -r '.operator_groups[].name|"vault_identity_group admin_"+(.|ascii_downcase|gsub("[/+. -]+";"_"))' "$CFG" | tr ' ' ':'); do need "${g%%:*}" "${g##*:}"; done

rm -f "$L/main.tf" "$L/outputs.tf" "$L/human_auth.tf" "$L/imports_admin_config.tf" "$L/admin_config_README.md"
mkdir -p "$L"
bash "$scaffold" "$L" admin >/dev/null

hdr() { printf '# Generated by vault-brownfield-codifier\n# Capability: admin-config\n# Doc ref: %s/%s\n# Namespace: admin\n\n' "$DOC" "$1"; }
PMAP=$(jq -c "$LIB"' map({key:.name, value:("admin/"+.name|lbl)}) | from_entries' "$RAW/admin/policies.json")

# ---- main.tf and outputs.tf -----------------------------------------------------------------------
{ hdr namespace
  jq -r --argjson pmap "$PMAP" "$LIB"'
    "locals {\n  operator_policies = [" + ([.operator_policies[] | "vault_policy.\($pmap[.]).name"] | join(", ")) + "]\n"
    + (if (.operator_groups|length) > 0 then "\n  operator_groups = {\n" + ([.operator_groups[] | "    \(.name|tojson) = vault_identity_group.\("admin/"+.name|lbl).name\n"] | join("")) + "  }\n" else "\n  operator_groups = {}\n" end)
    + "}\n"' "$CFG"
} > "$L/main.tf"

{ hdr namespace
  jq -r "$LIB"'
    ([.machine_auth_mounts[]?, .human_auth_mounts[]?] | sort_by(.path)) as $m
    | "output \"namespace_paths\" {\n  description = \"Namespace path of the admin layer.\"\n  value       = { admin = vault_namespace.admin.path }\n}\n\n"
    + "output \"operator_policy_names\" {\n  description = \"Names of the operator policies in the admin namespace.\"\n  value       = local.operator_policies\n}\n"
    + "\noutput \"operator_group_names\" {\n  description = \"Names of the identity groups that hold an operator policy.\"\n  value       = local.operator_groups\n}\n"
    + (if ($m|length) > 0 then "\noutput \"auth_mount_accessors\" {\n  description = \"Accessors of the auth mounts in the admin namespace.\"\n  value = {\n"
        + ([$m[] | "    \(.path|sub("/$";"")|tojson) = \(mref(.type; ("admin/"+(.path|sub("/$";""))|lbl))).accessor\n"] | join("")) + "  }\n}\n" else "" end)' "$CFG"
} > "$L/outputs.tf"

# ---- human_auth.tf -----------------------------------------------------------------------------------
nh=$(jq '[.human_auth_mounts[]? | select(.type|IN("oidc","jwt","ldap"))] | length' "$CFG")
if [ "$nh" -gt 0 ]; then
read -r -d '' HUMAN <<'JQ' || true
def s($k; $v): if ($v // "") != "" then "  \($k) = \($v|tojson)\n" else "" end;
def l($k; $v): if ($v // []) | length > 0 then "  \($k) = \($v|sort|tojson)\n" else "" end;
def n($k; $v): if ($v // 0) > 0 then "  \($k) = \($v)\n" else "" end;
def pols($pmap): if (. // []) | length > 0 then "  token_policies = [" + ([ . | sort[] | if $pmap[.] then "vault_policy.\($pmap[.]).name" else tojson end ] | join(", ")) + "]\n" else "" end;
def var($name; $what): "variable \"\($name)\" {\n  description = \"\($what)\"\n  type        = string\n  sensitive   = true\n}\n\n";
def lc($x): "\n  # provider 4.8.0 does not read these back after import; ignoring them avoids a no-op diff\n  lifecycle {\n    ignore_changes = [\($x)]\n  }\n";
[ .human_auth_mounts[] | select(.type|IN("oidc","jwt","ldap")) | . as $m
  | (.path|sub("/$";"")) as $p | ("admin/"+$p|lbl) as $lb | (.config // {}) as $c
  | if $m.type|IN("oidc","jwt") then
      ( if $m.type == "oidc" then var($lb+"_oidc_client_secret"; "OIDC client secret for mount \($p). Supply at plan time; Vault never returns it.") else "" end )
      + "resource \"vault_jwt_auth_backend\" \"\($lb)\" {\n  provider = vault.admin\n  type     = \($m.type|tojson)\n  path     = \($p|tojson)\n"
      + s("oidc_discovery_url"; $c.oidc_discovery_url) + s("oidc_client_id"; $c.oidc_client_id)
      + (if $m.type == "oidc" then "  oidc_client_secret = var.\($lb)_oidc_client_secret\n" else "" end)
      + s("bound_issuer"; $c.bound_issuer) + s("default_role"; $c.default_role) + s("jwks_url"; $c.jwks_url)
      + s("oidc_response_mode"; $c.oidc_response_mode) + l("oidc_response_types"; $c.oidc_response_types)
      + l("jwt_supported_algs"; $c.jwt_supported_algs) + l("jwt_validation_pubkeys"; $c.jwt_validation_pubkeys)
      + lc(if $m.type == "oidc" then "disable_remount, oidc_client_secret, tune" else "disable_remount, tune" end) + "}\n"
      + ([ ($m.roles_or_groups // [])[] | . as $r | ("admin/"+$p+"/"+$r.name|lbl) as $rl
          | "\nresource \"vault_jwt_auth_backend_role\" \"\($rl)\" {\n  provider  = vault.admin\n  backend   = vault_jwt_auth_backend.\($lb).path\n  role_name = \($r.name|tojson)\n"
          + s("role_type"; $r.role_type) + s("user_claim"; $r.user_claim) + s("groups_claim"; $r.groups_claim) + s("bound_subject"; $r.bound_subject)
          + l("bound_audiences"; $r.bound_audiences) + l("oidc_scopes"; $r.oidc_scopes) + l("allowed_redirect_uris"; $r.allowed_redirect_uris)
          + (($r.token_policies // $r.policies) | pols($pmap))
          + n("token_ttl"; $r.token_ttl) + n("token_max_ttl"; $r.token_max_ttl)
          + (if ($r.bound_claims // {}) != {} and (($r.bound_claims|to_entries|all(.value|type=="string"))) then "  bound_claims = {\n" + ($r.bound_claims|to_entries|sort_by(.key)|map("    \(.key|tojson) = \(.value|tojson)\n")|join("")) + "  }\n" else "" end)
          + "}\n" ] | join(""))
    else
      var($lb+"_bindpass"; "Bind password for LDAP mount \($p). Supply at plan time; Vault never returns it.")
      + "resource \"vault_ldap_auth_backend\" \"\($lb)\" {\n  provider = vault.admin\n  path     = \($p|tojson)\n"
      + s("url"; $c.url) + s("userdn"; $c.userdn) + s("userattr"; $c.userattr) + s("upndomain"; $c.upndomain) + s("binddn"; $c.binddn)
      + "  bindpass = var.\($lb)_bindpass\n"
      + s("groupdn"; $c.groupdn) + s("groupfilter"; $c.groupfilter) + s("groupattr"; $c.groupattr) + s("certificate"; $c.certificate)
      + (if $c.starttls == true then "  starttls = true\n" else "" end) + (if $c.insecure_tls == true then "  insecure_tls = true\n" else "" end)
      + (if $c.discoverdn == true then "  discoverdn = true\n" else "" end) + (if $c.deny_null_bind == false then "  deny_null_bind = false\n" else "" end)
      + lc("bindpass, disable_remount") + "}\n"
      + ([ ($m.roles_or_groups // [])[] | . as $g | ("admin/"+$p+"/"+$g.name|lbl) as $gl
          | "\nresource \"vault_ldap_auth_backend_group\" \"\($gl)\" {\n  provider  = vault.admin\n  backend   = vault_ldap_auth_backend.\($lb).path\n  groupname = \($g.name|tojson)\n"
          + ($g.policies | if (. // []) | length > 0 then "  policies  = [" + ([ sort[] | if $pmap[.] then "vault_policy.\($pmap[.]).name" else tojson end ] | join(", ")) + "]\n" else "" end)
          + "}\n" ] | join(""))
    end ] | join("\n")
JQ
  { hdr jwt_auth_backend; jq -r --argjson pmap "$PMAP" "$LIB $HUMAN" "$CFG"; } > "$L/human_auth.tf"
  { hdr jwt_auth_backend
    jq -r "$LIB"'
      [ .human_auth_mounts[] | select(.type|IN("oidc","jwt","ldap")) | . as $m | (.path|sub("/$";"")) as $p | ("admin/"+$p|lbl) as $lb
        | "import {\n  to = \(mref($m.type; $lb))\n  id = \($p|tojson)\n}\n"
          + ([ ($m.roles_or_groups // [])[] | ("admin/"+$p+"/"+.name|lbl) as $rl
              | if $m.type == "ldap" then "\nimport {\n  to = vault_ldap_auth_backend_group.\($rl)\n  id = \("auth/\($p)/groups/\(.name)"|tojson)\n}\n"
                else "\nimport {\n  to = vault_jwt_auth_backend_role.\($rl)\n  id = \("auth/\($p)/role/\(.name)"|tojson)\n}\n" end ] | join("")) ] | join("\n")' "$CFG"
  } > "$L/imports_admin_config.tf"
fi

# ---- README ----------------------------------------------------------------------------------------------
rootop=""; [ -s "$RAW/root/policies.json" ] && rootop=$(jq -r '[.[]|select(.name=="operator")]|length' "$RAW/root/policies.json")
{
  echo '# admin layer'; echo
  echo '## Operator policies'; echo
  echo '| Policy | Namespace | Held by |'
  echo '|---|---|---|'
  jq -r '. as $c | $c.operator_policies[] | . as $p
    | "| `\($p)` | admin | " + ([$c.operator_groups[] | select(.policies | index($p)) | .name] | if length == 0 then "(no recorded holder)" else join(", ") end) + " |"' "$CFG"
  [ "${rootop:-0}" -gt 0 ] && echo '| `operator` | root | Out of scope here; owned by root-config / policies |'
  echo; echo '## Human authentication'; echo
  jq -r '[.human_auth_mounts[]? | "`\(.path)` (\(.type))"] | if length == 0 then "No human auth method detected in `admin`." else "Detected: " + join(", ") + "." end' "$CFG"
  echo
  jq -r '[.machine_auth_mounts[]? | "`\(.path)` (\(.type))"] | if length == 0 then "" else "Machine auth mounts (" + join(", ") + ") and their roles are emitted by `auth-mounts` and referenced here, not declared." end' "$CFG"
  if [ "$nh" -gt 0 ]; then
    echo; echo 'Supply `TF_VAR_<label>_oidc_client_secret` or `TF_VAR_<label>_bindpass` at plan time. They have no default.'
    echo 'Role attributes not codified: non-string `bound_claims`, `claim_mappings`, `verbose_oidc_logging`, `tune`.'
  fi
} > "$L/admin_config_README.md"

"$TF" fmt -recursive "$L" >/dev/null
echo "admin-config: $(jq '.operator_policies|length' "$CFG") operator polic(ies), $(jq '.operator_groups|length' "$CFG") operator group(s), $nh human auth mount(s)"
