#!/usr/bin/env bash
# codification-auth-mounts (TASK-018)
#   generate.sh [raw-dir] [out-root]
# Reads <raw>/<ns>/auth_mounts.json for the root namespace and every namespace in <raw>/namespaces.json
# and writes under <out-root>:
#   admin/<ns>_auth_mounts.tf, admin/imports_auth_mounts.tf    root and `admin` mounts
#   seed/<ns>_auth_mounts.tf,  seed/imports_auth_mounts.tf     tenant mounts
#   auth-mounts/coverage.md
# Fully codified: vault_auth_backend (+ tune when it deviates from the defaults) and, for approle,
# vault_approle_auth_backend_role. Every other mount type gets the backend only; coverage.md lists
# what was not codified. role_id and secret_id are never written.
# Import IDs (task-006-decision.md): backend = bare path; role = auth/<path>/role/<name>.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
RAW=${1:-discovered_terraform/raw}
OUT=${2:-discovered_terraform/terraform}
TF=${TERRAFORM:-terraform}
DOC=https://registry.terraform.io/providers/hashicorp/vault/4.8.0/docs/resources
scaffold=$here/../../vault-codifier-conventions/scripts/scaffold-layer.sh
{ test -s "$RAW/namespaces.json" && jq -e 'type=="array"' "$RAW/namespaces.json" >/dev/null; } \
  || { echo "STOP: $RAW/namespaces.json missing or invalid" >&2; exit 2; }

dir_of() { if [ -z "$1" ]; then echo "$RAW/root"; else echo "$RAW/$1"; fi; }
nss=$( { echo ""; jq -r '.[] | select(.path != "" and .path != "root") | .path' "$RAW/namespaces.json"; } )

read -r -d '' LIB <<'JQ' || true
def lbl: ascii_downcase | gsub("[/+. -]+";"_") | gsub("_+";"_") | sub("^_";"") | sub("_$";"")
         | if test("^[0-9]") then "r_"+. else . end | if .=="" then "_empty" else . end;
def nsjoin($ns; $x): if $ns == "" then $x else $ns + "/" + $x end;
JQ

# ---- load: one record per mount, roles nested -----------------------------------
ALL='[]'
while IFS= read -r ns; do
  d=$(dir_of "$ns")
  [ -s "$d/auth_mounts.json" ] || { echo "STOP: $d/auth_mounts.json missing" >&2; exit 2; }
  jq -e '.mounts|type=="array"' "$d/auth_mounts.json" >/dev/null || { echo "STOP: $d/auth_mounts.json unreadable" >&2; exit 2; }
  # credential guard on exact key names (secret_id_ttl, bind_secret_id etc. are configuration)
  if jq -e '[.. | objects | keys[] | select(. == "role_id" or . == "secret_id" or . == "secret_id_accessor")] | length > 0' "$d/auth_mounts.json" >/dev/null; then
    echo "STOP: $d/auth_mounts.json contains a role_id/secret_id field (value not printed)" >&2; exit 2
  fi
  case "$ns" in ""|admin) layer=admin ;; *) layer=seed ;; esac
  pols='[]'; [ -s "$d/policies.json" ] && pols=$(cat "$d/policies.json")
  ALL=$(echo "$ALL" | jq -c --slurpfile m "$d/auth_mounts.json" --argjson pols "$pols" --arg ns "$ns" --arg layer "$layer" "$LIB"'
    ($pols | map({key:.name, value:(nsjoin($ns; .name)|lbl)}) | from_entries) as $pmap
    | . + [ $m[0].mounts[]
        | select(.path != "token" and .path != "token/")
        | select(($ns != "admin") or ((.type | IN("oidc","jwt","ldap")) | not))   # owned by codification-admin-config
        | (.path|sub("/$";"")) as $p
        | {ns:$ns, layer:$layer, nsl:(if $ns=="" then "root" else ($ns|lbl) end), p:$p,
           label:(nsjoin($ns;$p)|lbl), type:.type, description:(.description // ""),
           local:(.local // false), tune:(.tune // {}),
           roles:[ (.roles // [])[] | . + {
               rlabel:(nsjoin($ns; $p + "/" + .name)|lbl),
               pols:[ (.token_policies // []) | sort[] | if $pmap[.] then {ref:$pmap[.]} else {lit:.} end ] } ] } ]')
done <<< "$nss"

echo "$ALL" | jq -e '
  [ .[] | . as $m | {layer:$m.layer, label:$m.label, id:($m.ns+"/"+$m.p)},
          ($m.roles[] | {layer:$m.layer, label:.rlabel, id:($m.ns+"/"+$m.p+"/"+.name)}) ]
  | group_by([.layer,.label]) | map(select(length>1)|map(.id)) | length == 0' >/dev/null \
  || { echo "STOP: duplicate label within a layer" >&2; exit 2; }

hdr() { printf '# Generated by vault-brownfield-codifier\n# Capability: auth-mounts\n# Doc ref: %s/%s\n# Namespace: %s\n\n' "$DOC" "$1" "$2"; }

# ---- program that renders the resources of one namespace ---------------------------
read -r -d '' RENDER <<'JQ' || true
def prov: if $ns != "" then "  provider = vault.\($alias)\n" else "" end;
def lst($t; $k): if ($t[$k] // []) | length > 0 then "    \($k) = \($t[$k]|tojson)\n" else "" end;
def tune: . as $t
  | ( (if ($t.default_lease_ttl // 0) != 2764800 and ($t.default_lease_ttl // 0) != 0 then "    default_lease_ttl = \("\($t.default_lease_ttl)s"|tojson)\n" else "" end)
    + (if ($t.max_lease_ttl // 0) != 2764800 and ($t.max_lease_ttl // 0) != 0 then "    max_lease_ttl = \("\($t.max_lease_ttl)s"|tojson)\n" else "" end)
    + lst($t;"allowed_response_headers") + lst($t;"audit_non_hmac_request_keys")
    + lst($t;"audit_non_hmac_response_keys") + lst($t;"passthrough_request_headers")
    + (if ($t.listing_visibility // "") != "" then "    listing_visibility = \($t.listing_visibility|tojson)\n" else "" end)
    + (if ($t.token_type // "default-service") != "default-service" then "    token_type = \($t.token_type|tojson)\n" else "" end) )
  | if . == "" then "" else "\n  tune {\n" + . + "  }\n" end;
def num($k; $v): if ($v // 0) > 0 then "  \($k) = \($v)\n" else "" end;
def role($m): . as $r
  | "\nresource \"vault_approle_auth_backend_role\" \"\($r.rlabel)\" {\n" + prov
  + "  backend   = vault_auth_backend.\($m.label).path\n"
  + "  role_name = \($r.name|tojson)\n"
  + (if ($r.pols|length) > 0 then "  token_policies = [" + ($r.pols|map(if .ref then "vault_policy.\(.ref).name" else (.lit|tojson) end)|join(", ")) + "]\n" else "" end)
  + num("token_ttl"; $r.token_ttl) + num("token_max_ttl"; $r.token_max_ttl)
  + num("token_explicit_max_ttl"; $r.token_explicit_max_ttl) + num("token_period"; $r.token_period)
  + num("token_num_uses"; $r.token_num_uses)
  + (if $r.token_no_default_policy == true then "  token_no_default_policy = true\n" else "" end)
  + (if ($r.token_type // "default") != "default" then "  token_type = \($r.token_type|tojson)\n" else "" end)
  + (if ($r.token_bound_cidrs // []) | length > 0 then "  token_bound_cidrs = \($r.token_bound_cidrs|sort|tojson)\n" else "" end)
  + (if $r.bind_secret_id == false then "  bind_secret_id = false\n" else "" end)
  + num("secret_id_num_uses"; $r.secret_id_num_uses) + num("secret_id_ttl"; $r.secret_id_ttl)
  + (if ($r.secret_id_bound_cidrs // []) | length > 0 then "  secret_id_bound_cidrs = \($r.secret_id_bound_cidrs|sort|tojson)\n" else "" end)
  + "}\n";
[.[] | select(.ns == $ns)] | sort_by(.p) | map(
    . as $m
    | ($m.tune|tune) as $tb
    | "resource \"vault_auth_backend\" \"\($m.label)\" {\n" + prov
    + "  type = \($m.type|tojson)\n  path = \($m.p|tojson)\n"
    + (if $m.description != "" then "  description = \($m.description|tojson)\n" else "" end)
    + (if $m.local == true then "  local = true\n" else "" end)
    + $tb
    + "\n  # provider 4.8.0 imports disable_remount (and an untuned tune) as unset; ignoring them avoids a no-op diff\n  lifecycle {\n    ignore_changes = [" + (if $tb == "" then "disable_remount, tune" else "disable_remount" end) + "]\n  }\n}\n"
    + (if $m.type == "approle" then ([$m.roles | sort_by(.name)[] | role($m)] | join("")) else "" end)
  ) | join("\n")
JQ

for layer in admin seed; do
  sub=$(echo "$ALL" | jq -c --arg l "$layer" '[.[]|select(.layer==$l)]')
  L=$OUT/$layer
  rm -f "$L"/*_auth_mounts.tf "$L/imports_auth_mounts.tf"
  [ "$(echo "$sub" | jq length)" = 0 ] && continue
  mkdir -p "$L"
  aliases=(); for n in $(echo "$sub" | jq -r '[.[].ns|select(.!="")]|unique|.[]'); do aliases+=("$n"); done
  bash "$scaffold" "$L" ${aliases[@]+"${aliases[@]}"} >/dev/null

  for ns in $(echo "$sub" | jq -r '[.[].ns]|unique|.[]' | sed 's/^$/@root/'); do
    [ "$ns" = "@root" ] && ns=""
    nsl=$(echo "$sub" | jq -r --arg ns "$ns" '[.[]|select(.ns==$ns)][0].nsl')
    { hdr auth_backend "${ns:-(root)}"
      echo "$sub" | jq -r --arg ns "$ns" --arg alias "$nsl" "$LIB $RENDER"
    } > "$L/${nsl}_auth_mounts.tf"
  done
  { hdr auth_backend "(per resource provider)"
    echo "$sub" | jq -r '
      sort_by([.ns,.p]) | map(. as $m
        | "import {\n  to = vault_auth_backend.\($m.label)\n  id = \($m.p|tojson)\n}\n"
        + (if $m.type == "approle" then ([$m.roles|sort_by(.name)[] |
            "\nimport {\n  to = vault_approle_auth_backend_role.\(.rlabel)\n  id = \("auth/\($m.p)/role/\(.name)"|tojson)\n}\n"] | join("")) else "" end)) | join("\n")'
  } > "$L/imports_auth_mounts.tf"
done

# ---- coverage ------------------------------------------------------------------------
mkdir -p "$OUT/auth-mounts"
{
  echo '# Auth mount coverage'; echo
  echo '| Namespace | Mount | Type | Codified as | Roles | Notes |'
  echo '|---|---|---|---|---|---|'
  echo "$ALL" | jq -r 'sort_by([.ns,.p])[] |
    "| \(if .ns=="" then "root" else "`"+.ns+"`" end) | `\(.p)` | \(.type) | "
    + (if .type=="approle" then "`vault_auth_backend`, `vault_approle_auth_backend_role`" else "`vault_auth_backend` only" end)
    + " | \(.roles|length) | "
    + (if .type=="approle" then (if ([.roles[].pols[]|select(.lit)]|length)>0 then "policy not in namespace: " + ([.roles[].pols[]|select(.lit)|.lit]|unique|join(", ")) else "-" end)
       else "method configuration, roles and users are not codified: review manually" end) + " |"'
  echo
  echo "$ALL" | jq -r '"Mounts: \(length). Roles: \([.[].roles|length]|add // 0). Not fully codified: \([.[]|select(.type!="approle")]|length)."'
} > "$OUT/auth-mounts/coverage.md"

for l in admin seed; do [ -d "$OUT/$l" ] && "$TF" fmt -recursive "$OUT/$l" >/dev/null; done
echo "auth-mounts: $(echo "$ALL" | jq length) mount(s), $(echo "$ALL" | jq '[.[].roles|length]|add // 0') role(s)"
