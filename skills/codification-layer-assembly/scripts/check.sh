#!/usr/bin/env bash
# codification-layer-assembly (TASK-022): ownership and consistency checker
#   check.sh [out-root]
# Checks every state layer (a directory under <out-root> that holds providers.tf):
#   1. each .tf file starts with the provenance header and names a capability
#   2. each resource type is declared only by its owning capability (conventions section 2.4)
#   3. forbidden resource types are absent
#   4. no label is declared twice for one resource type in a layer (CAC6)
#   5. every resource has exactly one import {} block, and every import targets a declared resource
#      (vault_generic_endpoint cannot be imported and is exempt)
#   6. no UUID literal outside imports*.tf, no SYNTHETIC- string, no inline secret assignment
#   7. versions.tf and providers.tf exist
# Prints one VIOLATION line per problem (never a secret value). Exit 0 = none, 1 = at least one.
set -uo pipefail
OUT=${1:-discovered_terraform/terraform}
HEADER='# Generated by vault-brownfield-codifier'
fail=0
viol() { echo "VIOLATION: $*"; fail=$((fail + 1)); }

owner() {
  case "$1" in
    vault_kv_secret_v2|vault_kv_secret|vault_generic_secret|vault_approle_auth_backend_role_secret_id) echo forbidden ;;
    vault_namespace) echo namespaces ;;
    vault_policy|vault_egp_policy|vault_rgp_policy) echo policies ;;
    vault_jwt_auth_backend*|vault_ldap_auth_backend*) echo admin-config ;;
    vault_auth_backend|vault_approle_auth_backend*) echo auth-mounts ;;
    vault_mount|vault_kv_secret_backend_v2|vault_pki_secret_backend*|vault_database_secret_backend*|vault_aws_secret_backend*|vault_transit_secret_backend*|vault_ssh_secret_backend*) echo secrets-engines ;;
    vault_identity_*) echo teams ;;
    vault_audit|vault_quota_*|vault_generic_endpoint) echo root-config ;;
    *) echo unowned ;;
  esac
}

layers=0
for L in "$OUT"/*/; do
  L=${L%/}; [ -f "$L/providers.tf" ] || continue
  layers=$((layers + 1)); name=$(basename "$L")
  tmp=$(mktemp -d)
  : > "$tmp/res"; : > "$tmp/imp"

  for f in versions.tf providers.tf; do [ -f "$L/$f" ] || viol "$name: $f is missing"; done

  for f in "$L"/*.tf; do
    [ -e "$f" ] || continue
    b=$(basename "$f")
    if [ "$(head -n 1 "$f")" != "$HEADER" ]; then viol "$name/$b: provenance header missing"; fi
    cap=$(sed -n 's/^# Capability: //p' "$f" | head -n 1)
    [ -n "$cap" ] || viol "$name/$b: no '# Capability:' header line"
    # type label capability file
    awk -v cap="$cap" -v file="$name/$b" '
      /^resource "/ { t=$2; l=$3; gsub(/"/,"",t); gsub(/"/,"",l); print t, l, cap, file >> "'"$tmp"'/res" }
      /^import \{/ { inimp=1 }
      inimp && /^  to = / { split($3,a,"."); print a[1], a[2], cap, file >> "'"$tmp"'/imp"; inimp=0 }
    ' "$f"
  done

  # ownership and forbidden types (resources and imports)
  for kind in res imp; do
    while read -r t l cap file; do
      o=$(owner "$t")
      case "$o" in
        forbidden) viol "$file: forbidden $t.$l" ;;
        unowned)   viol "$file: $t.$l has no owning capability" ;;
        *) [ "$o" = "$cap" ] || viol "$file: $t.$l belongs to '$o' but the file is '$cap'" ;;
      esac
    done < "$tmp/$kind"
  done

  # duplicate labels per type
  sort "$tmp/res" | awk '{k=$1" "$2; n[k]++; f[k]=f[k]" "$4} END {for (k in n) if (n[k]>1) print k "|" f[k]}' \
    | while IFS='|' read -r k files; do echo "VIOLATION: $name: $k declared more than once in:$files"; done > "$tmp/dup"
  if [ -s "$tmp/dup" ]; then cat "$tmp/dup"; fail=$((fail + $(wc -l < "$tmp/dup"))); fi

  # one import per resource, one resource per import
  awk '{print $1"."$2}' "$tmp/res" | sort > "$tmp/res.k"
  awk '{print $1"."$2}' "$tmp/imp" | sort > "$tmp/imp.k"
  while read -r k; do
    t=${k%%.*}
    [ "$t" = vault_generic_endpoint ] && continue
    n=$(grep -cxF "$k" "$tmp/imp.k" || true)
    [ "$n" = 1 ] || viol "$name: $k has $n import blocks (expected 1)"
  done < <(sort -u "$tmp/res.k")
  while read -r k; do
    grep -qxF "$k" "$tmp/res.k" || viol "$name: import targets $k, which is not declared"
  done < <(sort -u "$tmp/imp.k")

  # secrets and UUID literals
  while IFS= read -r hit; do viol "$name: ${hit%%:*} holds a UUID literal outside imports"; done \
    < <(grep -lE '[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}' $(ls "$L"/*.tf | grep -v '/imports[^/]*\.tf$') 2>/dev/null | sed "s#^$OUT/##; s#\$#:#")
  while IFS= read -r hit; do viol "$name: ${hit%%:*} contains SYNTHETIC-"; done \
    < <(grep -l 'SYNTHETIC-' "$L"/*.tf 2>/dev/null | sed "s#^$OUT/##; s#\$#:#")
  while IFS= read -r hit; do viol "$name: ${hit%%:*} assigns an inline secret literal"; done \
    < <(grep -lE '(secret_id|bindpass|client_secret|oidc_client_secret|private_key|password)[[:space:]]*=[[:space:]]*"[^"]' "$L"/*.tf 2>/dev/null | sed "s#^$OUT/##; s#\$#:#")

  echo "layer $name: $(sort -u "$tmp/res.k" | wc -l | tr -d ' ') resource(s), $(sort -u "$tmp/imp.k" | wc -l | tr -d ' ') import(s)"
  rm -rf "$tmp"
done

[ "$layers" -gt 0 ] || { echo "VIOLATION: no layer found under $OUT"; exit 1; }
if [ "$fail" -gt 0 ]; then echo "ownership check: $fail violation(s)"; exit 1; fi
echo "ownership check: 0 violations"
