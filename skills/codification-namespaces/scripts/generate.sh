#!/usr/bin/env bash
# codification-namespaces (TASK-015)
#   generate.sh [namespaces.json] [out-root]
# Reads the discovery payload and writes, under <out-root> (default discovered_terraform/terraform):
#   admin/{namespaces,imports}.tf                         depth-1 namespaces (default provider)
#   namespaces/{namespaces,imports}.tf, hierarchy.md      depth >= 2 (parent's provider alias)
#   versions.tf + providers.tf for both layers
# Children use `provider = vault.<parent label>`; there is no namespace argument and no parent path
# string in a vault_namespace block. Import IDs are the leaf name (task-006-decision.md).
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
IN=${1:-discovered_terraform/raw/namespaces.json}
OUT=${2:-discovered_terraform/terraform}
TF=${TERRAFORM:-terraform}
DOC=https://registry.terraform.io/providers/hashicorp/vault/4.8.0/docs/resources/namespace
{ test -s "$IN" && jq -e 'type=="array"' "$IN" >/dev/null; } || { echo "STOP: $IN missing or invalid" >&2; exit 2; }

LABEL='ascii_downcase | gsub("[/+. -]+";"_") | gsub("_+";"_") | sub("^_";"") | sub("_$";"")
       | if test("^[0-9]") then "r_"+. else . end | if .=="" then "_empty" else . end'

# Records: root dropped, depth/leaf/parent/label added, sorted parent-before-child.
recs=$(jq -S -c "
  def lbl: $LABEL;
  [ .[] | select(.path != \"\" and .path != \"root\")
    | . + {depth:(.path|split(\"/\")|length), leaf:(.path|split(\"/\")|last),
           parent:(.path|split(\"/\")|.[:-1]|join(\"/\")), label:(.path|lbl)} ]
  | sort_by([.depth,.path])" "$IN")

[ "$(echo "$recs" | jq length)" = 0 ] && { echo "no namespaces"; exit 0; }

echo "$recs" | jq -e '
  (map(.path)) as $all
  | (map(select(.parent != "" and ((.parent | IN($all[])) | not))) | map(.path)) as $orphans
  | (group_by(.label) | map(select(length > 1) | map(.path))) as $dups
  | if ($orphans|length) > 0 then error("orphan: " + ($orphans|join(",")))
    elif ($dups|length) > 0 then error("duplicate label: " + ($dups|tostring)) else true end' >/dev/null \
  || { echo "STOP: orphan namespace or duplicate label" >&2; exit 2; }

hdr() { printf '# Generated by vault-brownfield-codifier\n# Capability: namespaces\n# Doc ref: %s\n# Namespace: %s\n\n' "$DOC" "$1"; }

emit() { # emit <layer> <depth filter> <header namespace>
  local layer=$1 filter=$2 ns=$3 dir=$OUT/$1 sub
  mkdir -p "$dir"
  sub=$(echo "$recs" | jq -c "[.[] | select($filter)]")
  if [ "$(echo "$sub" | jq length)" = 0 ]; then rm -f "$dir/namespaces.tf" "$dir/imports.tf"; return; fi
  {
    hdr "$ns"
    echo "$sub" | jq -r "
      def plabel: $LABEL;
      (map(.label)) as \$here
      | map(
          \"resource \\\"vault_namespace\\\" \\\"\\(.label)\\\" {\\n\"
          + (if .depth >= 2 then \"  provider = vault.\\(.parent|plabel)\\n\" else \"\" end)
          + \"  path     = \\\"\\(.leaf)\\\"\\n\"
          + (if (.parent|plabel) as \$p | (\$here|index(\$p)) != null then \"  depends_on = [vault_namespace.\\(.parent|plabel)]\\n\" else \"\" end)
          + (if (.custom_metadata // {}) | length > 0
             then \"\\n  custom_metadata = {\\n\" + (.custom_metadata|to_entries|sort_by(.key)|map(\"    \\(.key) = \\(.value|tojson)\")|join(\"\\n\")) + \"\\n  }\\n\"
             else \"\" end)
          + \"}\\n\") | join(\"\\n\")"
  } > "$dir/namespaces.tf"
  {
    hdr "$ns"
    echo "$sub" | jq -r 'map("import {\n  to = vault_namespace.\(.label)\n  id = \(.leaf|tojson)\n}\n") | join("\n")'
  } > "$dir/imports.tf"
}

emit admin      '.depth == 1'  '(root)'
emit namespaces '.depth >= 2'  '(parent provider alias)'

scaffold=$here/../../vault-codifier-conventions/scripts/scaffold-layer.sh
bash "$scaffold" "$OUT/admin"
parents=$(echo "$recs" | jq -r '[.[] | select(.depth >= 2) | .parent] | unique | .[]')
# shellcheck disable=SC2086
bash "$scaffold" "$OUT/namespaces" $parents

{
  echo '# Namespace hierarchy'; echo
  echo '```mermaid'; echo 'graph TD'
  echo "$recs" | jq -r '
    def nid: gsub("[^A-Za-z0-9]";"_");
    (.[] | "  \(.path|nid)[\"\(.path) (depth \(.depth))\"]"),
    (.[] | select(.parent != "") | "  \(.parent|nid) --> \(.path|nid)")'
  echo '```'; echo
  echo '| Full path | Parent | Id | custom_metadata | Depth |'
  echo '|---|---|---|---|---|'
  echo "$recs" | jq -r '.[] | "| `\(.path)` | \(if .parent=="" then "root" else "`"+.parent+"`" end) | `\(.id)` | \(if (.custom_metadata // {})|length>0 then (.custom_metadata|to_entries|sort_by(.key)|map("\(.key) = \(.value)")|join(", ")) else "none" end) | \(.depth) |"'
} > "$OUT/namespaces/hierarchy.md"

"$TF" fmt -recursive "$OUT" >/dev/null
