#!/usr/bin/env bash
# codification-policies (TASK-017)
#   generate.sh [raw-dir] [out-root]
# Reads <raw>/<ns>/policies.json (+ auth_mounts.json, identity.json for correlation) for the root
# namespace and every namespace in <raw>/namespaces.json, and writes under <out-root>:
#   admin/<ns>_policies.tf, admin/imports_policies.tf, admin/policies/<ns>/<name>.hcl   (root and `admin`)
#   seed/ ...same shape...                                                              (tenant namespaces)
#   <layer>/<ns>_sentinel.tf, <layer>/imports_sentinel.tf, <layer>/policies/sentinel/<ns>/<name>.sentinel (EGP and RGP)
#   policies/correlation.{md,json}, policies/coverage.md                                (analysis, not a layer)
# Policy text is copied byte-for-byte. > 10 lines (or anything unsafe in a heredoc) goes to a .hcl file.
# Import ID is the bare policy name, relative to the provider alias's namespace (task-006-decision.md).
# EGP and RGP (CAP-008) read <raw>/<ns>/sentinel.json; the Sentinel source always goes to a .sentinel file, byte-for-byte.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
RAW=${1:-discovered_terraform/raw}
OUT=${2:-discovered_terraform/terraform}
TF=${TERRAFORM:-terraform}
DOC=https://registry.terraform.io/providers/hashicorp/vault/4.8.0/docs/resources/policy
DOC_EGP=https://registry.terraform.io/providers/hashicorp/vault/4.8.0/docs/resources/egp_policy
DOC_RGP=https://registry.terraform.io/providers/hashicorp/vault/4.8.0/docs/resources/rgp_policy
scaffold=$here/../../vault-codifier-conventions/scripts/scaffold-layer.sh
{ test -s "$RAW/namespaces.json" && jq -e 'type=="array"' "$RAW/namespaces.json" >/dev/null; } \
  || { echo "STOP: $RAW/namespaces.json missing or invalid" >&2; exit 2; }

LABEL='ascii_downcase | gsub("[/+. -]+";"_") | gsub("_+";"_") | sub("^_";"") | sub("_$";"")
       | if test("^[0-9]") then "r_"+. else . end | if .=="" then "_empty" else . end'
lbl() { jq -rn --arg s "$1" "def lbl: $LABEL; \$s | lbl"; }
dir_of() { if [ -z "$1" ]; then echo "$RAW/root"; else echo "$RAW/$1"; fi; }

# namespace list: root ("") first, then every namespace path
nss=$( { echo ""; jq -r '.[] | select(.path != "" and .path != "root") | .path' "$RAW/namespaces.json"; } )

ALL='[]'
while IFS= read -r ns; do
  f=$(dir_of "$ns")/policies.json
  [ -s "$f" ] || { echo "STOP: $f missing" >&2; exit 2; }
  jq -e 'type=="array" and all(.[]; has("name") and (.policy_text|type=="string"))' "$f" >/dev/null \
    || { echo "STOP: $f unreadable or a policy lacks policy_text" >&2; exit 2; }
  case "$ns" in ""|admin) layer=admin ;; *) layer=seed ;; esac
  ALL=$(echo "$ALL" | jq -c --slurpfile p "$f" --arg ns "$ns" --arg layer "$layer" "def lbl: $LABEL;
    . + [\$p[0][] | select(.name != \"default\" and .name != \"root\" and .name != \"default-ceiling\")
         | {ns:\$ns, layer:\$layer, name:.name, text:.policy_text,
            nsl:(if \$ns==\"\" then \"root\" else (\$ns|lbl) end),
            label:(if \$ns==\"\" then .name|lbl else (\$ns+\"/\"+.name)|lbl end)}]")
done <<< "$nss"

# safety: file-name safety and unique labels per layer
echo "$ALL" | jq -e '
  (map(select(.name|test("^[A-Za-z0-9._-]+$")|not))|map(.name)) as $badname
  | (group_by([.layer,.label])|map(select(length>1)|map(.ns+"/"+.name))) as $dups
  | if ($badname|length)>0 then error("unsafe policy name: "+($badname|join(",")))
    elif ($dups|length)>0 then error("duplicate label: "+($dups|tostring)) else true end' >/dev/null \
  || { echo "STOP: unsafe policy name or duplicate label (see jq error above)" >&2; exit 2; }

ALL=$(echo "$ALL" | jq -c '
  map(. + {file:((.text|rtrimstr("\n")|split("\n")|length) > 10
              or (.text|endswith("\n")|not) or (.text|test("\r|\t|\\$\\{|%\\{|(^|\n)EOT"))) })')

hdr() { printf '# Generated by vault-brownfield-codifier\n# Capability: policies\n# Doc ref: %s\n# Namespace: %s\n\n' "$DOC" "$1"; }

for layer in admin seed; do
  sub=$(echo "$ALL" | jq -c --arg l "$layer" '[.[]|select(.layer==$l)]')
  L=$OUT/$layer
  rm -rf "$L/policies"; rm -f "$L"/*_policies.tf "$L/imports_policies.tf"
  [ "$(echo "$sub" | jq length)" = 0 ] && continue
  mkdir -p "$L"
  aliases=()
  for ns in $(echo "$sub" | jq -r '[.[].ns|select(.!="")]|unique|.[]'); do aliases+=("$ns"); done
  bash "$scaffold" "$L" ${aliases[@]+"${aliases[@]}"} >/dev/null

  for ns in $(echo "$sub" | jq -r '[.[].ns]|unique|.[]' | sed 's/^$/@root/'); do
    [ "$ns" = "@root" ] && ns=""
    nsl=$(echo "$sub" | jq -r --arg ns "$ns" '[.[]|select(.ns==$ns)][0].nsl')
    disp=${ns:-"(root)"}; dirn=$(echo "$nsl" | sed 's/^$/root/')
    pdir=$(if [ -z "$ns" ]; then echo root; else echo "${ns//\//__}"; fi)
    # write .hcl bodies verbatim
    echo "$sub" | jq -r --arg ns "$ns" '.[]|select(.ns==$ns and .file)|.name' | while IFS= read -r n; do
      mkdir -p "$L/policies/$pdir"
      echo "$sub" | jq -j --arg ns "$ns" --arg n "$n" '.[]|select(.ns==$ns and .name==$n)|.text' > "$L/policies/$pdir/$n.hcl"
    done
    {
      hdr "$disp"
      echo "$sub" | jq -r --arg ns "$ns" --arg pdir "$pdir" --arg alias "$nsl" '
        [.[]|select(.ns==$ns)] | sort_by(.name) | map(
          "resource \"vault_policy\" \"\(.label)\" {\n"
          + (if $ns != "" then "  provider = vault.\($alias)\n" else "" end)
          + "  name = \(.name|tojson)\n"
          + (if .file then "  policy = file(\"${path.module}/policies/\($pdir)/\(.name).hcl\")\n"
             else "  policy = <<-EOT\n"
                  + (.text|rtrimstr("\n")|split("\n")|map(if .=="" then "" else "    "+. end)|join("\n"))
                  + "\n  EOT\n" end)
          + "}\n") | join("\n")'
    } > "$L/${dirn}_policies.tf"
  done
  {
    hdr "(per resource provider)"
    echo "$sub" | jq -r 'sort_by([.ns,.name]) | map("import {\n  to = vault_policy.\(.label)\n  id = \(.name|tojson)\n}\n") | join("\n")'
  } > "$L/imports_policies.tf"
done

# ---- Sentinel (EGP and RGP, CAP-008) ---------------------------------------------
SALL='[]'
while IFS= read -r ns; do
  f=$(dir_of "$ns")/sentinel.json
  [ -s "$f" ] || continue
  jq -e 'type=="object" and all((.egp,.rgp)[]?; has("name") and (.policy_text|type=="string") and has("enforcement_level"))' "$f" >/dev/null \
    || { echo "STOP: $f unreadable or a Sentinel policy lacks policy_text or enforcement_level" >&2; exit 2; }
  case "$ns" in ""|admin) layer=admin ;; *) layer=seed ;; esac
  SALL=$(echo "$SALL" | jq -c --slurpfile p "$f" --arg ns "$ns" --arg layer "$layer" "def lbl: $LABEL;
    . + [(\$p[0].egp[]? | . + {kind:\"egp\"}), (\$p[0].rgp[]? | . + {kind:\"rgp\"})
         | {ns:\$ns, layer:\$layer, kind:.kind, name:.name, text:.policy_text, level:.enforcement_level, paths:(.paths // []),
            nsl:(if \$ns==\"\" then \"root\" else (\$ns|lbl) end),
            label:(if \$ns==\"\" then .name|lbl else (\$ns+\"/\"+.name)|lbl end)}]")
done <<< "$nss"
echo "$SALL" | jq -e '
  (map(select(.name|test("^[A-Za-z0-9._-]+$")|not))|map(.name)) as $badname
  | (group_by([.layer,.kind,.label])|map(select(length>1)|map(.ns+"/"+.name))) as $dups
  | if ($badname|length)>0 then error("unsafe Sentinel policy name: "+($badname|join(",")))
    elif ($dups|length)>0 then error("duplicate Sentinel label: "+($dups|tostring)) else true end' >/dev/null \
  || { echo "STOP: unsafe Sentinel policy name or duplicate label (see jq error above)" >&2; exit 2; }

shdr() { printf '# Generated by vault-brownfield-codifier\n# Capability: policies\n# Doc ref: %s\n# Namespace: %s\n\n' "$1" "$2"; }
for layer in admin seed; do
  sub=$(echo "$SALL" | jq -c --arg l "$layer" '[.[]|select(.layer==$l)]')
  L=$OUT/$layer
  rm -rf "$L/policies/sentinel"; rm -f "$L"/*_sentinel.tf "$L/imports_sentinel.tf"
  [ "$(echo "$sub" | jq length)" = 0 ] && continue
  mkdir -p "$L"
  aliases=()
  for ns in $(echo "$sub" | jq -r '[.[].ns|select(.!="")]|unique|.[]'); do aliases+=("$ns"); done
  bash "$scaffold" "$L" ${aliases[@]+"${aliases[@]}"} >/dev/null
  for ns in $(echo "$sub" | jq -r '[.[].ns]|unique|.[]' | sed 's/^$/@root/'); do
    [ "$ns" = "@root" ] && ns=""
    nsl=$(echo "$sub" | jq -r --arg ns "$ns" '[.[]|select(.ns==$ns)][0].nsl')
    disp=${ns:-"(root)"}
    pdir=$(if [ -z "$ns" ]; then echo root; else echo "${ns//\//__}"; fi)
    mkdir -p "$L/policies/sentinel/$pdir"
    echo "$sub" | jq -r --arg ns "$ns" '.[]|select(.ns==$ns)|[.kind,.name]|@tsv' | while IFS=$'\t' read -r k n; do
      echo "$sub" | jq -j --arg ns "$ns" --arg k "$k" --arg n "$n" '.[]|select(.ns==$ns and .kind==$k and .name==$n)|.text' > "$L/policies/sentinel/$pdir/$k-$n.sentinel"
    done
    {
      shdr "$DOC_EGP (vault_egp_policy), $DOC_RGP (vault_rgp_policy)" "$disp"
      echo "$sub" | jq -r --arg ns "$ns" --arg pdir "$pdir" --arg alias "$nsl" '
        [.[]|select(.ns==$ns)] | sort_by([.kind,.name]) | map(
          "resource \"vault_\(.kind)_policy\" \"\(.label)\" {\n"
          + (if $ns != "" then "  provider = vault.\($alias)\n" else "" end)
          + "  name = \(.name|tojson)\n"
          + "  enforcement_level = \(.level|tojson)\n"
          + (if .kind=="egp" then "  paths = [\(.paths|map(gsub("\\$\\{";"$${")|gsub("%\\{";"%%{")|tojson)|join(", "))]\n" else "" end)
          + "  policy = file(\"${path.module}/policies/sentinel/\($pdir)/\(.kind)-\(.name).sentinel\")\n"
          + "}\n") | join("\n")'
    } > "$L/${nsl}_sentinel.tf"
  done
  {
    shdr "$DOC_EGP, $DOC_RGP" "(per resource provider)"
    echo "$sub" | jq -r 'sort_by([.ns,.kind,.name]) | map("import {\n  to = vault_\(.kind)_policy.\(.label)\n  id = \(.name|tojson)\n}\n") | join("\n")'
  } > "$L/imports_sentinel.tf"
done

# ---- correlation ------------------------------------------------------------
mkdir -p "$OUT/policies"
corr='[]'
while IFS= read -r ns; do
  d=$(dir_of "$ns")
  am='{"mounts":[]}'; [ -s "$d/auth_mounts.json" ] && am=$(cat "$d/auth_mounts.json")
  idn='{"groups":[],"entities":[]}'; [ -s "$d/identity.json" ] && idn=$(cat "$d/identity.json")
  corr=$(jq -c -n --argjson corr "$corr" --argjson all "$ALL" --argjson am "$am" --argjson idn "$idn" --arg ns "$ns" '
    ([$all[]|select(.ns==$ns)|.name]) as $have
    | ([$am.mounts[]? as $m | $m.roles[]? | {kind:"auth_role", src:($m.path+"/"+.name), pols:((.token_policies // .policies // [])) }]
       + [$idn.groups[]?   | {kind:"group",  src:.name, pols:(.policies // [])}]
       + [$idn.entities[]? | {kind:"entity", src:.name, pols:(.policies // [])}]) as $refs
    | $corr + [ ($have[] | . as $p | {namespace:$ns, policy:$p,
          auth_roles:[$refs[]|select(.kind=="auth_role" and (.pols|index($p)))|.src]|sort,
          groups:[$refs[]|select(.kind=="group" and (.pols|index($p)))|.src]|sort,
          entities:[$refs[]|select(.kind=="entity" and (.pols|index($p)))|.src]|sort,
          dangling:false}),
        ($refs[] | . as $r | $r.pols[] | select(. != "default" and . != "root" and . != "default-ceiling" and ((. as $x | $have|index($x))|not))
          | {namespace:$ns, policy:., kind:$r.kind, referenced_by:$r.src, dangling:true}) ]')
done <<< "$nss"
echo "$corr" | jq -S 'sort_by([.namespace,.policy,(.referenced_by//"")])' > "$OUT/policies/correlation.json"

{
  echo '# Policy correlation matrix'; echo
  echo 'Which auth roles, identity groups and entities reference each policy. Generated from discovery payloads.'; echo
  while IFS= read -r ns; do
    echo "## ${ns:-root}"; echo
    echo '| Policy | Auth roles | Groups | Entities |'; echo '|---|---|---|---|'
    jq -r --arg ns "$ns" '.[]|select(.namespace==$ns and .dangling==false)
      | "| `\(.policy)` | \(if (.auth_roles|length)>0 then (.auth_roles|map("`"+.+"`")|join(", ")) else "-" end) | \(if (.groups|length)>0 then (.groups|map("`"+.+"`")|join(", ")) else "-" end) | \(if (.entities|length)>0 then (.entities|map("`"+.+"`")|join(", ")) else "-" end) |"' "$OUT/policies/correlation.json"
    dang=$(jq -r --arg ns "$ns" '.[]|select(.namespace==$ns and .dangling==true)|"- `\(.policy)` (dangling) referenced by \(.kind) `\(.referenced_by)`"' "$OUT/policies/correlation.json")
    [ -n "$dang" ] && { echo; echo "$dang"; }
    echo
  done <<< "$nss"
} > "$OUT/policies/correlation.md"

{
  echo '# Sentinel policy coverage (EGP / RGP)'; echo
  if [ -s "$RAW/coverage.json" ]; then
    jq -r '.policies | "ACL policies discovered: \(.acl_total)\n\n- EGP: \(if (.egp_policies|length)==0 then "none discovered" else (.egp_policies|join(", ")) end)\n- RGP: \(if (.rgp_policies|length)==0 then "none discovered" else (.rgp_policies|join(", ")) end)"' "$RAW/coverage.json"
    echo; echo 'Emitted as `vault_egp_policy` and `vault_rgp_policy`; the Sentinel source is copied byte-for-byte to `policies/sentinel/<namespace>/<kind>-<name>.sentinel`.'
    echo; echo '| Namespace | EGP | RGP |'; echo '|---|---|---|'
    while IFS= read -r ns; do
      echo "$SALL" | jq -r --arg ns "$ns" '[.[]|select(.ns==$ns)] as $x
        | "| \(if $ns=="" then "root" else $ns end) | \([$x[]|select(.kind=="egp")]|length|if .==0 then "none" else tostring end) | \([$x[]|select(.kind=="rgp")]|length|if .==0 then "none" else tostring end) |"'
    done <<< "$nss"
    if [ "$(echo "$SALL" | jq length)" -gt 0 ]; then
      echo; echo '| Policy | Namespace | Kind | Enforcement | Paths |'; echo '|---|---|---|---|---|'
      echo "$SALL" | jq -r 'sort_by([.ns,.kind,.name])[] | "| `\(.name)` | \(if .ns=="" then "root" else .ns end) | \(.kind|ascii_upcase) | \(.level) | \(if .kind=="egp" then (.paths|map("`"+.+"`")|join(", ")) else "n/a" end) |"'
    fi
  else
    echo 'unavailable (coverage.json missing)'
  fi
} > "$OUT/policies/coverage.md"

for l in admin seed; do [ -d "$OUT/$l" ] && "$TF" fmt -recursive "$OUT/$l" >/dev/null; done
echo "policies: $(echo "$ALL" | jq length) vault_policy, $(echo "$SALL" | jq '[.[]|select(.kind=="egp")]|length') vault_egp_policy, $(echo "$SALL" | jq '[.[]|select(.kind=="rgp")]|length') vault_rgp_policy; admin=$(echo "$ALL" | jq '[.[]|select(.layer=="admin")]|length') seed=$(echo "$ALL" | jq '[.[]|select(.layer=="seed")]|length')"
