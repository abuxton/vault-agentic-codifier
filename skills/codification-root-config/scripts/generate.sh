#!/usr/bin/env bash
# codification-root-config (TASK-016)
#   generate.sh [raw-root-dir] [out-root]
# Reads discovered_terraform/raw/root/*.json and writes, into the `admin` layer under <out-root>/admin:
#   audit.tf, quotas.tf, imports_root_config.tf, root_config_README.md
# Root-namespace resources: no provider alias and no namespace argument.
# Licence text is never read into the output (ID and expiry only).
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
IN=${1:-discovered_terraform/raw/root}
OUT=${2:-discovered_terraform/terraform}
TF=${TERRAFORM:-terraform}
D=$OUT/admin
DOC=https://registry.terraform.io/providers/hashicorp/vault/4.8.0/docs/resources
mkdir -p "$D"

[ -s "$IN/audit.json" ] && jq -e 'type=="object"' "$IN/audit.json" >/dev/null \
  || { echo "STOP: $IN/audit.json missing or invalid (sys/audit read failed)" >&2; exit 2; }

LABEL='ascii_downcase | gsub("[/+. -]+";"_") | gsub("_+";"_") | sub("^_";"") | sub("_$";"")
       | if test("^[0-9]") then "r_"+. else . end | if .=="" then "_empty" else . end'

hdr() { printf '# Generated by vault-brownfield-codifier\n# Capability: root-config\n# Doc ref: %s/%s\n# Namespace: (root)\n\n' "$DOC" "$1"; }

# ---- audit devices ---------------------------------------------------------
audit=$(jq -S -c "def lbl: $LABEL;
  [to_entries[] | .value + {key:.key} | . + {p:(.path // .key | sub(\"/\$\";\"\")), } | . + {label:(.p|lbl)}] | sort_by(.p)" "$IN/audit.json")
echo "$audit" | jq -e '
  (map(select(.options|to_entries|any(.key|test("password|secret|token|credential";"i")))) | map(.p)) as $bad
  | if ($bad|length)>0 then error("secret-like option key in audit device: "+($bad|join(","))) else true end' >/dev/null \
  || { echo "STOP: audit options contain a secret-like key (value not printed)" >&2; exit 2; }
echo "$audit" | jq -e '(group_by(.label)|map(select(length>1))|length)==0' >/dev/null \
  || { echo "STOP: duplicate audit labels" >&2; exit 2; }

if [ "$(echo "$audit" | jq length)" = 0 ]; then
  rm -f "$D/audit.tf"
else
  { hdr audit
    echo "$audit" | jq -r 'map(
      "resource \"vault_audit\" \"\(.label)\" {\n  type = \(.type|tojson)\n  path = \(.p|tojson)\n"
      + (if (.description // "") != "" then "  description = \(.description|tojson)\n" else "" end)
      + (if .local == true then "  local = true\n" else "" end)
      + "\n  options = {\n"
      + (.options|to_entries|sort_by(.key)|map("    \(.key) = \(.value|tostring|tojson)")|join("\n"))
      + "\n  }\n}\n") | join("\n")'
  } > "$D/audit.tf"
fi

# ---- rate-limit quotas -----------------------------------------------------
quotas='[]'
if [ -s "$IN/quotas_rate_limit_list.json" ]; then
  while IFS= read -r n; do
    f="$IN/quota_rate_limit_$(echo "$n" | tr '-' '_').json"
    [ -s "$f" ] || { echo "STOP: quota payload $f missing" >&2; exit 2; }
    quotas=$(echo "$quotas" | jq -c --slurpfile q "$f" '. + $q')
  done < <(jq -r '.keys[]' "$IN/quotas_rate_limit_list.json")
fi
quotas=$(echo "$quotas" | jq -S -c "def lbl: $LABEL; map(. + {label:(.name|lbl)}) | sort_by(.name)")
echo "$quotas" | jq -e '(group_by(.label)|map(select(length>1))|length)==0' >/dev/null \
  || { echo "STOP: duplicate quota labels" >&2; exit 2; }

if [ "$(echo "$quotas" | jq length)" = 0 ]; then
  rm -f "$D/quotas.tf"
else
  { hdr quota_rate_limit
    echo "$quotas" | jq -r 'map(
      "resource \"vault_quota_rate_limit\" \"\(.label)\" {\n"
      + "  name = \(.name|tojson)\n  path = \(.path|tojson)\n  rate = \(.rate)\n"
      + (if (.interval // 0) > 0 then "  interval = \(.interval)\n" else "" end)
      + (if (.block_interval // 0) > 0 then "  block_interval = \(.block_interval)\n" else "" end)
      # inheritable is not read back by provider 4.8.0 on import; omitted to keep the plan at zero diff
      + (if (.role // "") != "" then "  role = \(.role|tojson)\n" else "" end)
      + "}\n") | join("\n")'
  } > "$D/quotas.tf"
fi

# ---- imports ---------------------------------------------------------------
n_imp=$(( $(echo "$audit" | jq length) + $(echo "$quotas" | jq length) ))
if [ "$n_imp" = 0 ]; then
  rm -f "$D/imports_root_config.tf"
else
  { hdr audit
    echo "$audit"  | jq -r 'map("import {\n  to = vault_audit.\(.label)\n  id = \(.p|tojson)\n}\n") | join("\n")'
    echo "$quotas" | jq -r 'map("import {\n  to = vault_quota_rate_limit.\(.label)\n  id = \(.name|tojson)\n}\n") | join("\n")'
  } | sed '/^$/N;/^\n$/D' > "$D/imports_root_config.tf"
fi

# ---- README: not managed by Terraform --------------------------------------
j() { jq -r "$2" "$IN/$1" 2>/dev/null || echo "unavailable"; }
seal=$(j seal_status.json '.type')
lic_id=$(j license_status.json '.autoloaded.license_id')
lic_exp=$(j license_status.json '.autoloaded.expiration_time')
perf=$(j replication_status.json '.performance.mode')
dr=$(j replication_status.json '.dr.mode')
nhdr=0; [ -s "$IN/ui_headers.json" ] && nhdr=$(jq '.keys // [] | length' "$IN/ui_headers.json")
{
  echo '# Root configuration: not managed by Terraform'; echo
  echo 'Generated by vault-brownfield-codifier (capability: root-config). Audit devices and rate-limit quotas'
  echo 'are codified in `audit.tf` and `quotas.tf`. The items below cannot be codified.'; echo
  echo '| Item | Value discovered | Why not codified |'
  echo '|---|---|---|'
  echo "| Seal type | \`$seal\` | Set in the server config file, not the API |"
  echo "| Licence | ID \`$lic_id\`, expires \`$lic_exp\` | Auto-loaded from file or env at start; text is never recorded |"
  echo "| Replication mode | performance \`$perf\`, dr \`$dr\` | Enabled by operator workflow; activation tokens are secrets |"
  echo; [ "$(echo "$audit" | jq length)" = 0 ] && echo 'No audit devices were discovered.' || true
  if [ "$nhdr" != 0 ]; then
    echo "$nhdr custom UI header(s) were discovered under \`sys/config/ui/headers\`. Header values are not read by discovery, so they are not codified."
  else
    echo 'No custom UI headers were discovered.'
  fi
  if [ "$perf" = disabled ] && [ "$dr" = disabled ]; then echo "Replication is disabled, so no \`replication.tf\` is generated."
  elif [ "$perf" = unavailable ]; then echo "Replication status was not available; check it manually."
  else echo "Replication is enabled: review it manually; it is not codified."; fi
} > "$D/root_config_README.md"

[ -f "$D/versions.tf" ] || bash "$here/../../vault-codifier-conventions/scripts/scaffold-layer.sh" "$D" >/dev/null
"$TF" fmt -recursive "$D" >/dev/null
echo "root-config: $(echo "$audit" | jq length) audit, $(echo "$quotas" | jq length) quota -> $D"
