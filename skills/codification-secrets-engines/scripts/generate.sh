#!/usr/bin/env bash
# codification-secrets-engines (TASK-019)
#   generate.sh [raw-dir] [out-root]
# Reads <raw>/<ns>/secrets_engines.json for the root namespace and every namespace in <raw>/namespaces.json
# and writes under <out-root>:
#   admin/<ns>_secrets_engines.tf, admin/imports_secrets_engines.tf   root and `admin` mounts
#   seed/<ns>_secrets_engines.tf,  seed/imports_secrets_engines.tf    tenant mounts
#   secrets-engines/coverage.md
# Fully codified: vault_mount for every type and, for KV v2, vault_kv_secret_backend_v2.
# Other engine types get the mount only; coverage.md lists what was not codified.
# Secret data is never read. vault_kv_secret_v2, vault_kv_secret and vault_generic_secret are never emitted.
# Import IDs (task-006-decision.md): vault_mount = bare path; vault_kv_secret_backend_v2 = <path>/config.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
RAW=${1:-discovered_terraform/raw}
OUT=${2:-discovered_terraform/terraform}
TF=${TERRAFORM:-terraform}
DOC=https://registry.terraform.io/providers/hashicorp/vault/4.8.0/docs/resources
scaffold=$here/../../vault-codifier-conventions/scripts/scaffold-layer.sh
{ test -s "$RAW/namespaces.json" && jq -e 'type=="array"' "$RAW/namespaces.json" >/dev/null; } \
  || { echo "STOP: $RAW/namespaces.json missing or invalid" >&2; exit 2; }

dir_of() { if [ -z "$1" ]; then echo "$RAW/root"; else echo "$RAW/$1"; fi; }
nss=$( { echo ""; jq -r '.[] | select(.path != "" and .path != "root") | .path' "$RAW/namespaces.json"; } )

read -r -d '' LIB <<'JQ' || true
def lbl: ascii_downcase | gsub("[/+. -]+";"_") | gsub("_+";"_") | sub("^_";"") | sub("_$";"")
         | if test("^[0-9]") then "r_"+. else . end | if .=="" then "_empty" else . end;
def nsjoin($ns; $x): if $ns == "" then $x else $ns + "/" + $x end;
JQ

# ---- load: one record per mount ------------------------------------------------------
ALL='[]'
while IFS= read -r ns; do
  d=$(dir_of "$ns")
  [ -s "$d/secrets_engines.json" ] || { echo "STOP: $d/secrets_engines.json missing" >&2; exit 2; }
  jq -e '.mounts|type=="array"' "$d/secrets_engines.json" >/dev/null || { echo "STOP: $d/secrets_engines.json unreadable" >&2; exit 2; }
  # credential guard on exact key names; engine_config of KV holds only versioning settings
  if jq -e '[.. | objects | keys[] | select(. == "password" or . == "secret_key" or . == "private_key" or . == "token" or . == "data")] | length > 0' "$d/secrets_engines.json" >/dev/null; then
    echo "STOP: $d/secrets_engines.json contains a credential field (value not printed)" >&2; exit 2
  fi
  case "$ns" in ""|admin) layer=admin ;; *) layer=seed ;; esac
  ALL=$(echo "$ALL" | jq -c --slurpfile m "$d/secrets_engines.json" --arg ns "$ns" --arg layer "$layer" "$LIB"'
    . + [ $m[0].mounts[]
        | select(.path != "sys/" and .path != "identity/" and .path != "cubbyhole/")
        | (.path|sub("/$";"")) as $p
        | {ns:$ns, layer:$layer, nsl:(if $ns=="" then "root" else ($ns|lbl) end), p:$p,
           label:(nsjoin($ns;$p)|lbl), type:.type, description:(.description // ""),
           local:(.local // false), seal_wrap:(.seal_wrap // false), options:(.options // {}),
           plugin_version:(.plugin_version // ""), tune:(.tune // {}),
           kv2:(.type == "kv" and ((.options // {}).version == "2")),
           cfg:(.engine_config // {})} ]')
done <<< "$nss"

echo "$ALL" | jq -e '
  [ .[] | {layer:.layer, label:.label, id:(.ns+"/"+.p)} ]
  | group_by([.layer,.label]) | map(select(length>1)) | length == 0' >/dev/null \
  || { echo "STOP: duplicate label within a layer" >&2; exit 2; }

hdr() { printf '# Generated by vault-brownfield-codifier\n# Capability: secrets-engines\n# Doc ref: %s/%s\n# Namespace: %s\n\n' "$DOC" "$1" "$2"; }

# ---- program that renders the resources of one namespace ---------------------------
read -r -d '' RENDER <<'JQ' || true
def prov: if $ns != "" then "  provider = vault.\($alias)\n" else "" end;
# Vault reports 0 (use system default) and 2764800 (the system default itself); neither is emitted.
def ttl($k; $v): if ($v // 0) != 0 and ($v // 0) != 2764800 then "  \($k) = \($v)\n" else "" end;
def lst($k; $v): if ($v // []) | length > 0 then "  \($k) = \($v|sort|tojson)\n" else "" end;
def opts: if length > 0 then "  options = {\n" + (to_entries|sort_by(.key)|map("    \(.key) = \(.value|tojson)\n")|join("")) + "  }\n" else "" end;
[.[] | select(.ns == $ns)] | sort_by(.p) | map(
    . as $m
    | "resource \"vault_mount\" \"\($m.label)\" {\n" + prov
    + "  path = \($m.p|tojson)\n  type = \($m.type|tojson)\n"
    + (if $m.description != "" then "  description = \($m.description|tojson)\n" else "" end)
    + ($m.options|opts)
    + ttl("default_lease_ttl_seconds"; $m.tune.default_lease_ttl)
    + ttl("max_lease_ttl_seconds"; $m.tune.max_lease_ttl)
    + lst("allowed_response_headers"; $m.tune.allowed_response_headers)
    + lst("audit_non_hmac_request_keys"; $m.tune.audit_non_hmac_request_keys)
    + lst("audit_non_hmac_response_keys"; $m.tune.audit_non_hmac_response_keys)
    + lst("passthrough_request_headers"; $m.tune.passthrough_request_headers)
    + (if $m.seal_wrap then "  seal_wrap = true\n" else "" end)
    + (if $m.local then "  local = true\n" else "" end)
    + (if $m.plugin_version != "" then "  plugin_version = \($m.plugin_version|tojson)\n" else "" end)
    + "}\n"
    + (if $m.kv2 then
        "\nresource \"vault_kv_secret_backend_v2\" \"\($m.label)\" {\n" + prov
        + "  mount = vault_mount.\($m.label).path\n"
        + (if ($m.cfg.max_versions // 0) > 0 then "  max_versions = \($m.cfg.max_versions)\n" else "" end)
        + (if $m.cfg.cas_required == true then "  cas_required = true\n" else "" end)
        + (if ($m.cfg.delete_version_after // "0s") != "0s" then "  delete_version_after = \($m.cfg.delete_version_after|tojson)\n" else "" end)
        + "}\n"
      else "" end)
  ) | join("\n")
JQ

for layer in admin seed; do
  sub=$(echo "$ALL" | jq -c --arg l "$layer" '[.[]|select(.layer==$l)]')
  L=$OUT/$layer
  rm -f "$L"/*_secrets_engines.tf "$L/imports_secrets_engines.tf"
  [ "$(echo "$sub" | jq length)" = 0 ] && continue
  mkdir -p "$L"
  aliases=(); for n in $(echo "$sub" | jq -r '[.[].ns|select(.!="")]|unique|.[]'); do aliases+=("$n"); done
  bash "$scaffold" "$L" ${aliases[@]+"${aliases[@]}"} >/dev/null

  for ns in $(echo "$sub" | jq -r '[.[].ns]|unique|.[]' | sed 's/^$/@root/'); do
    [ "$ns" = "@root" ] && ns=""
    nsl=$(echo "$sub" | jq -r --arg ns "$ns" '[.[]|select(.ns==$ns)][0].nsl')
    { hdr mount "${ns:-(root)}"
      echo "$sub" | jq -r --arg ns "$ns" --arg alias "$nsl" "$LIB $RENDER"
    } > "$L/${nsl}_secrets_engines.tf"
  done
  { hdr mount "(per resource provider)"
    echo "$sub" | jq -r '
      sort_by([.ns,.p]) | map(. as $m
        | "import {\n  to = vault_mount.\($m.label)\n  id = \($m.p|tojson)\n}\n"
        + (if $m.kv2 then "\nimport {\n  to = vault_kv_secret_backend_v2.\($m.label)\n  id = \("\($m.p)/config"|tojson)\n}\n" else "" end)) | join("\n")'
  } > "$L/imports_secrets_engines.tf"
done

# ---- coverage ------------------------------------------------------------------------
mkdir -p "$OUT/secrets-engines"
{
  echo '# Secrets engine coverage'; echo
  echo '| Namespace | Mount | Type | Codified as | Notes |'
  echo '|---|---|---|---|---|'
  echo "$ALL" | jq -r 'sort_by([.ns,.p])[] |
    "| \(if .ns=="" then "root" else "`"+.ns+"`" end) | `\(.p)` | \(.type)\(if .kv2 then " (v2)" else "" end) | "
    + (if .kv2 then "`vault_mount`, `vault_kv_secret_backend_v2`" else "`vault_mount` only" end) + " | "
    + (if .kv2 then "secret data is never read" elif .type == "kv" then "KV v1: mount only; secret data is never read" else "engine configuration and roles are not codified: review manually" end)
    + (if .ns == "" and .p == "secret" then "; preloaded root mount (Vault dev mode) is imported, not created" else "" end) + " |"'
  echo
  echo "$ALL" | jq -r '"Mounts: \(length). Not fully codified: \([.[]|select(.kv2|not)]|length)."'
} > "$OUT/secrets-engines/coverage.md"

for l in admin seed; do [ -d "$OUT/$l" ] && "$TF" fmt -recursive "$OUT/$l" >/dev/null; done
echo "secrets-engines: $(echo "$ALL" | jq length) mount(s), $(echo "$ALL" | jq '[.[]|select(.kv2)]|length') KV v2 config(s)"
