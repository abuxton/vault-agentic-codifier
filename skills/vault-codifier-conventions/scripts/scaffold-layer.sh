#!/usr/bin/env bash
# scaffold-layer.sh <layer-dir> [namespace-path ...]
# Writes versions.tf and providers.tf for one state layer (conventions section 7).
# The default provider targets the root namespace; each namespace-path gets an alias
# `vault.<label>` (label = conventions section 5 applied to the path). Credentials are
# variables, never literals. Aliases accumulate in <layer>/.namespaces so several generators can
# share one layer without overwriting each other; re-running is byte-identical.
set -euo pipefail
layer=$1; shift
mkdir -p "$layer"
label() { echo "$1" | tr "A-Z" "a-z" | sed -E 's#[/+. -]+#_#g; s#_+#_#g; s#^_|_$##g' | sed -E "s#^([0-9])#r_\1#"; }

mkdir -p "$layer"
{ [ -f "$layer/.namespaces" ] && cat "$layer/.namespaces"; for n in "$@"; do echo "$n"; done; } | { grep -v "^\$" || true; } | LC_ALL=C sort -u > "$layer/.namespaces.new"
mv "$layer/.namespaces.new" "$layer/.namespaces"
set -- $(cat "$layer/.namespaces")

cat > "$layer/versions.tf" <<'EOF'
# Generated by vault-brownfield-codifier
# Capability: layer-assembly
# Doc ref: https://registry.terraform.io/providers/hashicorp/vault/4.8.0/docs
# Namespace: (root)

terraform {
  required_version = ">= 1.9"

  required_providers {
    vault = {
      source  = "hashicorp/vault"
      version = "~> 4"
    }
  }
}

variable "vault_address" {
  description = "Vault cluster address. Falls back to VAULT_ADDR."
  type        = string
  default     = null
}

variable "vault_token" {
  description = "Vault token for this layer. Falls back to VAULT_TOKEN."
  type        = string
  sensitive   = true
  default     = null
}
EOF

{
  cat <<'EOF'
# Generated by vault-brownfield-codifier
# Capability: layer-assembly
# Doc ref: https://registry.terraform.io/providers/hashicorp/vault/4.8.0/docs
# Namespace: (root)

provider "vault" {
  address          = var.vault_address
  token            = var.vault_token
  skip_child_token = true
}
EOF
  for ns in "$@"; do
    printf '\nprovider "vault" {\n  alias            = "%s"\n  address          = var.vault_address\n  token            = var.vault_token\n  namespace        = "%s"\n  skip_child_token = true\n}\n' "$(label "$ns")" "$ns"
  done
} > "$layer/providers.tf"
